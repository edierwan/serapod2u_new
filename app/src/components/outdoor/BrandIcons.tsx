/** Gmail's logo only for Gmail addresses; any other mailbox gets a plain envelope. */
export function EmailLogo({ email, className = 'h-4 w-4' }: IconProps & { email: string }) {
  const domain = email.split('@')[1]?.toLowerCase() || ''
  if (domain === 'gmail.com' || domain === 'googlemail.com') return <GmailLogo className={className} />
  return (
    <span className={`grid place-items-center rounded-[4px] bg-sky-600 ${className}`} aria-hidden>
      <Mail className="h-[70%] w-[70%] text-white" strokeWidth={2.5} />
    </span>
  )
}

